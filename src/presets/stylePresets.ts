function makeSpec(
  partial: Partial<TextStyleSpec> &
    Pick<TextStyleSpec, "fontZh" | "fontEn" | "sizePt">
): TextStyleSpec {
  return {
    bold: false,
    italic: false,
    color: "#1E293B",
    align: "left",
    lineSpacingRule: "multiple",
    lineSpacingValue: 1.5,
    spaceBeforePt: 0,
    spaceAfterPt: 6,
    firstLineIndentChars: 0,
    keepWithNext: false,
    borderBottom: false,
    ...partial,
  };
}

